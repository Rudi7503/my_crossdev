; ==============================================================================
; EXTREME OPTIMIZED 68080 ADPCM 6-BIT DECODER SUITE (Core 11350)
; Enthält: Stereo (L/R), Mid-Side (M/S) und Mono (15-Byte-Block = 20 Codes)
;
; Optimierungen (2026-10-26):
;   1. Vorberechnete Signed-32-Bit-Delta-Tabelle (delta6_table, 89 * 64 Longs):
;      Direkter Tabellenzugriff (a4,d1.w*4) ersetzt die komplette 6-Bit-IMA-
;      Shift/Branch-Kette (bis zu 6 btst-Branches pro Sample!) + Vorzeichenprüfung.
;   2. Inline-Makros (DEC_L6, DEC_R6) statt bsr/rts-Subroutinen pro Sample.
;   3. 24-Bit / 3-Byte Lade-Trick:
;      5 Chunks * 3 Bytes = 15 Bytes pro Block; je 3-Byte-Chunk (24 Bit) werden
;      exakt 4 Codes à 6 Bit (2 Stereo-Paare bzw. 4 Mono-Samples) extrahiert.
;   4. Register-Belegung:
;      - d0: aktueller 6-Bit-ADPCM-Code (0..63, Bit 5 = Sign, Bits 4..0 = Magnitude)
;      - d1: einziges Scratch-Register für Tabellen-Index, Delta und 32-Bit-Pack
;      - d2/d3: PCM-Prädiktor (32-Bit signed) & Step-Index (0..88) Links/Mid/Mono
;      - d4/d5: PCM-Prädiktor (32-Bit signed) & Step-Index (0..88) Rechts/Side
;      - d6/d7: äußerer (5 Chunks) / innerer (2 Paare bzw. 4 Mono-Samples) dbf-Zähler
;      - e0: 32-Bit-Bitstream-Schieberegister
;      - e2: Startwert des Hardware-Taktzählers (CCC) für Zyklusmessung
;      - a0/a1: Eingabe-Bitstream / Ausgabe-PCM-Puffer
;      - a4: Zeiger auf delta6_table (89 * 64 signed 32-Bit Deltas)
;      - a6: Zeiger auf index_adj_6bit (32 * 16-Bit Index-Adjust)
; ==============================================================================

; ------------------------------------------------------------------------------
; MACRO: DEC_L6 – Dekodiert einen 6-Bit-Code in d0 (0..63) für Links / Mid / Mono
; Aktualisiert d2 (PCM Links/Mid/Mono, geclampt auf -32768..32767) und d3 (Index 0..88).
; Nutzt ausschließlich d1 als Scratch-Register (d6/d7 bleiben unangetastet!).
; ------------------------------------------------------------------------------
DEC_L6 MACRO
            move.w  d3,d1                   ; d1 = aktueller Step-Index Links/Mid/Mono (0..88)
            lsl.w   #6,d1                   ; d1 = index * 64 (64 Einträge pro Step-Index)
            add.w   d0,d1                   ; d1 = index * 64 + code (0..63, inkl. Vorzeichenbit)
            move.l  (a4,d1.w*4),d1          ; d1 = vorberechnetes signed 32-Bit-Delta aus delta6_table
            add.l   d1,d2                   ; Neuen PCM-Wert berechnen: PCM_L += delta
            cmp.l   #32767,d2               ; 16-Bit Sättigung ( Obere Grenze +32767 )
            ble.s   .lmin\@
            move.l  #32767,d2
            bra.s   .lq\@
.lmin\@:
            cmp.l   #-32768,d2              ; 16-Bit Sättigung ( Untere Grenze -32768 )
            bge.s   .lq\@
            move.l  #-32768,d2
.lq\@:
            andi.w  #31,d0                  ; Vorzeichenbit (Bit 5) ausblenden -> Magnitude (0..31)
            add.w   (a6,d0.w*2),d3          ; Step-Index anpassen aus index_adj_6bit
            tst.w   d3                      ; Index-Clamping (0..88)
            bge.s   .lmax\@
            moveq   #0,d3
            bra.s   .li\@
.lmax\@:
            cmp.w   #88,d3
            ble.s   .li\@
            move.w  #88,d3
.li\@:
        ENDM

; ------------------------------------------------------------------------------
; MACRO: DEC_R6 – Dekodiert einen 6-Bit-Code in d0 (0..63) für Kanal Rechts / Side
; Aktualisiert d4 (PCM Rechts/Side, geclampt auf -32768..32767) und d5 (Index 0..88).
; ------------------------------------------------------------------------------
DEC_R6 MACRO
            move.w  d5,d1                   ; d1 = aktueller Step-Index Rechts/Side (0..88)
            lsl.w   #6,d1                   ; d1 = index * 64
            add.w   d0,d1                   ; d1 = index * 64 + code (0..63)
            move.l  (a4,d1.w*4),d1          ; d1 = signed 32-Bit-Delta aus delta6_table
            add.l   d1,d4                   ; PCM_R += delta
            cmp.l   #32767,d4               ; Clamping +32767
            ble.s   .rmin\@
            move.l  #32767,d4
            bra.s   .rq\@
.rmin\@:
            cmp.l   #-32768,d4              ; Clamping -32768
            bge.s   .rq\@
            move.l  #-32768,d4
.rq\@:
            andi.w  #31,d0                  ; Magnitude (0..31) isolieren
            add.w   (a6,d0.w*2),d5          ; Step-Index Rechts/Side anpassen
            tst.w   d5                      ; Clamping 0..88
            bge.s   .rmax\@
            moveq   #0,d5
            bra.s   .ri\@
.rmax\@:
            cmp.w   #88,d5
            ble.s   .ri\@
            move.w  #88,d5
.ri\@:
        ENDM

