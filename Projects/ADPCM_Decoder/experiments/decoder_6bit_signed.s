; ==============================================================================
; 1. DECODER: 6-BIT STEREO
; ==============================================================================
_decode_6bit_stereo_asm:
            movem.l d2-d7/a2-a6,-(a7)

            movec   ccc,d0
            move.l  d0,e2           

            move.l  48(a7),a0               ; A0 = in_buffer
            move.l  52(a7),a1               ; A1 = out_buffer
            move.l  56(a7),a5               ; A5 = chL
            move.l  60(a7),a3               ; A3 = chR
            ; 64(a7) = block_cnt

            move.l  (a5),d2                 ; D2 = PCM Links
            move.w  4(a5),d3        
            ext.l   d3                      ; D3 = Index Links

            move.l  (a3),d4                 ; D4 = PCM Rechts
            move.w  4(a3),d5        
            ext.l   d5                      ; D5 = Index Rechts

            lea     delta6_table(pc),a4       
            lea     index_adj_6bit(pc),a6   

            tst.l   64(a7)                  
            beq     .st_done

.st_block_loop:
            ; 15 Bytes Block = 5 Chunks à 3 Bytes (24 Bits) -> 20 Samples total
            moveq   #4,d6                   ; 5 Durchläufe (4 bis 0)
.st_chunk_loop:
            ; --- DER 32-BIT LOAD / 24-BIT PROCESS TRICK (LITTLE-ENDIAN FIX) ---
            movex.l (a0),e0
            ror.w   #8,e0                   ; Unteres Word anpassen
            swap    e0                      
            ror.w   #8,e0                   ; Oberes Word anpassen
            
            addq.l  #3,a0                   ; Lesezeiger exakt 3 Bytes weiterrücken!

            ; 24 Bits = 2 Stereo-Paare (2 x 12 Bits = 24 Bits)
            moveq   #1,d7                   ; Schleife läuft 2x
.st_pair_loop:
            move.l  e0,d0                   ; Links dekodieren
            andi.l  #63,d0                  ; 6-Bit Maske (0-63)
            DEC_L6          

            lsr.l   #6,e0                   ; Bitstream 6 Bits weiter schieben
            
            move.l  e0,d0                   ; Rechts dekodieren
            andi.l  #63,d0           
            DEC_R6        

            move.w  d2,d1                   ; 32-Bit Packing [Links | Rechts]
            swap    d1              
            move.w  d4,d1           
            move.l  d1,(a1)+                ; Ins RAM flashen

            lsr.l   #6,e0                   ; Bitstream 6 Bits weiter schieben
            dbf     d7,.st_pair_loop
            
            dbf     d6,.st_chunk_loop       
            
            subq.l  #1,64(a7)               ; block_cnt--
            bne     .st_block_loop

.st_done:
            move.l  56(a7),a5               
            move.l  d2,(a5)         
            move.w  d3,4(a5)        
            move.l  60(a7),a3       
            move.l  d4,(a3)         
            move.w  d5,4(a3)        

            movem.l (a7)+,d2-d7/a2-a6       
            
            movec   ccc,d0                  
            move.l  e2,d1           
            sub.l   d1,d0                   
            rts


; ==============================================================================
; 2. DECODER: 6-BIT MID-SIDE (M/S MATRIX)
; ==============================================================================
_decode_6bit_ms_asm:
            movem.l d2-d7/a2-a6,-(a7)

            movec   ccc,d0                  
            move.l  d0,e2           

            move.l  48(a7),a0               
            move.l  52(a7),a1               
            move.l  56(a7),a5               
            move.l  60(a7),a3               

            move.l  (a5),d2                 
            move.w  4(a5),d3        
            ext.l   d3                      

            move.l  (a3),d4                 
            move.w  4(a3),d5        
            ext.l   d5                      

            lea     delta6_table(pc),a4       
            lea     index_adj_6bit(pc),a6
            
            tst.l   64(a7)                  
            beq     .ms_done

.ms_block_loop:
            moveq   #4,d6                   ; 5 Chunks à 3 Bytes
.ms_chunk_loop:
            movex.l (a0),e0
            ror.w   #8,e0
            swap    e0
            ror.w   #8,e0
            addq.l  #3,a0

            moveq   #1,d7                   ; 2 M/S-Paare
.ms_pair_loop:
            move.l  e0,d0                   ; Mid dekodieren
            andi.l  #63,d0           
            DEC_L6          

            lsr.l   #6,e0                   ; Side dekodieren
            move.l  e0,d0           
            andi.l  #63,d0           
            DEC_R6        

            ; --- MATRIX (L = Mid+Side, R = Mid-Side) ---
            move.l  d2,d0           
            add.l   d4,d0                   ; D0 = Links
            move.l  d2,d1           
            sub.l   d4,d1                   ; D1 = Rechts

            ; Clamping Links (D0)
            cmp.l   #32767,d0
            ble     .ms_chk_min_L
            move.l  #32767,d0
            bra     .ms_clamp_R
.ms_chk_min_L:
            cmp.l   #-32768,d0
            bge     .ms_clamp_R
            move.l  #-32768,d0
            
.ms_clamp_R:
            ; Clamping Rechts (D1)
            cmp.l   #32767,d1
            ble     .ms_chk_min_R
            move.l  #32767,d1
            bra     .ms_pack
.ms_chk_min_R:
            cmp.l   #-32768,d1
            bge     .ms_pack
            move.l  #-32768,d1

.ms_pack:
            swap    d0                      ; 32-Bit Packing
            move.w  d1,d0           
            move.l  d0,(a1)+        

            lsr.l   #6,e0           
            dbf     d7,.ms_pair_loop
            dbf     d6,.ms_chunk_loop

            subq.l  #1,64(a7)
            bne     .ms_block_loop

.ms_done:
            move.l  56(a7),a5               
            move.l  d2,(a5)         
            move.w  d3,4(a5)        
            move.l  60(a7),a3       
            move.l  d4,(a3)         
            move.w  d5,4(a3)        

            movem.l (a7)+,d2-d7/a2-a6       
            
            movec   ccc,d0                  
            move.l  e2,d1           
            sub.l   d1,d0                   
            rts


; ==============================================================================
; 3. DECODER: 6-BIT MONO
; ==============================================================================
_decode_6bit_mono_asm:
            movem.l d2-d7/a2-a6,-(a7)       

            movec   ccc,d0                  
            move.l  d0,e2           

            move.l  48(a7),a0               
            move.l  52(a7),a1               
            move.l  56(a7),a5               

            move.l  (a5),d2                 
            move.w  4(a5),d3        
            ext.l   d3                      

            lea     delta6_table(pc),a4       
            lea     index_adj_6bit(pc),a6
            
            tst.l   60(a7)                  
            beq     .mo_done

.mo_block_loop:
            moveq   #4,d6                   ; 5 Chunks à 3 Bytes
.mo_chunk_loop:
            movex.l (a0),e0
            ror.w   #8,e0
            swap    e0
            ror.w   #8,e0
            addq.l  #3,a0

            moveq   #3,d7                   ; 4 Mono-Samples pro 3-Byte Chunk (4 * 6 = 24 Bits)
.mo_sample_loop:
            move.l  e0,d0           
            andi.l  #63,d0                  ; 6-Bit Maske
            DEC_L6          

            move.w  d2,(a1)+                ; Schreibt 16-Bit Mono RAM
            
            lsr.l   #6,e0                   ; 6 Bits weiter schieben
            dbf     d7,.mo_sample_loop
            dbf     d6,.mo_chunk_loop

            subq.l  #1,60(a7)               ; block_cnt--
            bne     .mo_block_loop

.mo_done:
            move.l  56(a7),a5               
            move.l  d2,(a5)         
            move.w  d3,4(a5)        

            movem.l (a7)+,d2-d7/a2-a6       
            
            movec   ccc,d0                  
            move.l  e2,d1           
            sub.l   d1,d0                   
            rts


